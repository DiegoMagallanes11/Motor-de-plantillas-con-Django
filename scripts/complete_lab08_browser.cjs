const fs=require('node:fs');const path=require('node:path');
const{chromium}=require('C:/Users/Magal/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
  const out=path.resolve('deliverables/lab08/evidence');
  const token=JSON.parse(fs.readFileSync('.private/quiz_tokens.json')).human;
  const id=JSON.parse(fs.readFileSync('.private/ui-lab08-target.json')).id;
  const steps=JSON.parse(fs.readFileSync('.private/ui-lab08-state.json'));
  const b=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
  const p=await b.newPage({viewport:{width:1440,height:1050},extraHTTPHeaders:{Authorization:'Token '+token}});
  const url='http://127.0.0.1:8008/api/exams/'+id+'/';
  await p.goto(url,{waitUntil:'networkidle'});
  await p.getByText('Raw data',{exact:true}).click();
  await p.locator('textarea[name=_content]').fill(JSON.stringify({title:'Cambio parcial desde API navegable'}));
  let [response]=await Promise.all([p.waitForResponse(r=>r.request().method()==='PATCH'),p.getByRole('button',{name:'PATCH',exact:true}).click()]);
  if(response.status()!==200)throw new Error('UI PATCH failed');
  await p.waitForLoadState('networkidle');
  steps.push({operation:'partial update',status:response.status()});
  await p.screenshot({path:path.join(out,'browser-patch-200.png'),fullPage:true});
  await p.getByRole('button',{name:/^delete$/i}).click();
  [response]=await Promise.all([p.waitForResponse(r=>r.request().method()==='DELETE'),p.locator('.modal button.btn-danger').click()]);
  await p.waitForLoadState('networkidle');
  const displayed=(await p.locator('pre').allTextContents()).join('\n');
  steps.push({operation:'delete',status:response.status(),displayed204:displayed.includes('204')});
  await p.screenshot({path:path.join(out,'browser-delete.png'),fullPage:true});
  response=await p.goto(url,{waitUntil:'networkidle'});
  if(response.status()!==404)throw new Error('UI target was not deleted');
  steps.push({operation:'retrieve deleted',status:404});
  await p.screenshot({path:path.join(out,'browser-deleted-404.png'),fullPage:true});
  response=await p.goto('http://127.0.0.1:8008/api/docs/',{waitUntil:'networkidle'});
  await p.screenshot({path:path.join(out,'browser-openapi.png'),fullPage:true});
  fs.writeFileSync(path.join(out,'browser-results.json'),JSON.stringify({steps,docsStatus:response.status()},null,2));
  console.log(JSON.stringify(steps));await b.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
